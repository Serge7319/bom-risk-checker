"use client";

import { useEffect, useState } from "react";
import { useParams, useRouter } from "next/navigation";
import { Shell } from "@/components/Shell";
import { fetchReport, getSession, type Report, type Session } from "@/lib/api";

export default function ReportPage() {
  const params = useParams<{ id: string }>();
  const router = useRouter();
  const [session, setLocalSession] = useState<Session | null>(null);
  const [report, setReport] = useState<Report | null>(null);
  const [error, setError] = useState("");

  useEffect(() => {
    const current = getSession();
    if (!current) {
      router.replace("/login");
      return;
    }
    setLocalSession(current);
    fetchReport(params.id, current.access_token)
      .then(setReport)
      .catch((err) =>
        setError(err instanceof Error ? err.message : "Failed to load report"),
      );
  }, [params.id, router]);

  if (!session) return null;

  return (
    <Shell session={session}>
      <section className="cv-hero cv-card">
        <h1>Analysis report</h1>
        <p>
          Synthetic preview report generated by the migration API using Cadivor
          parse, risk, and health modules.
        </p>
      </section>

      {error ? <div className="cv-error">{error}</div> : null}

      {report ? (
        <>
          <div className="cv-kpis">
            <div className="cv-kpi">
              <span>Components</span>
              <strong>{report.total_parts}</strong>
            </div>
            <div className="cv-kpi">
              <span>Health</span>
              <strong>
                {report.health_score == null ? "—" : `${report.health_score}/100`}
              </strong>
            </div>
            <div className="cv-kpi">
              <span>High risk</span>
              <strong>{report.high_risk_count}</strong>
            </div>
            <div className="cv-kpi">
              <span>Status</span>
              <strong style={{ fontSize: 16 }}>{report.health_status}</strong>
            </div>
          </div>

          <section className="cv-card">
            <h2 style={{ marginTop: 0, fontSize: 18 }}>
              {report.filename || "BOM"} · {report.mode}
            </h2>
            {report.summary_message ? (
              <p style={{ color: "#64748b", fontSize: 13 }}>
                {report.summary_message}
              </p>
            ) : null}
            <div style={{ overflowX: "auto" }}>
              <table className="cv-table">
                <thead>
                  <tr>
                    <th>MPN</th>
                    <th>Manufacturer</th>
                    <th>Qty</th>
                    <th>Lifecycle</th>
                    <th>Stock</th>
                    <th>Risk</th>
                  </tr>
                </thead>
                <tbody>
                  {report.parts.map((part) => (
                    <tr key={String(part.MPN)}>
                      <td>{String(part.MPN)}</td>
                      <td>{String(part.Manufacturer || "")}</td>
                      <td>{String(part.Quantity ?? "")}</td>
                      <td>{String(part.Lifecycle || "")}</td>
                      <td>{String(part.Stock ?? "")}</td>
                      <td>{String(part["Risk Level"] || "")}</td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          </section>
        </>
      ) : !error ? (
        <section className="cv-card" style={{ marginTop: 16 }}>
          Loading report…
          <div className="cv-progress" aria-hidden>
            <i />
          </div>
        </section>
      ) : null}
    </Shell>
  );
}
